def binary_metrics(y_true, y_score, threshold: float = 0.5, prefix: str = "") -> Dict[str, float]:
    y_true = np.asarray(y_true).astype(int)
    y_score = np.asarray(y_score).astype(float)
    y_pred = (y_score >= threshold).astype(int)

    out = {}
    p = prefix
    out[p + "n"] = int(len(y_true))
    out[p + "pos"] = int(np.sum(y_true == 1))
    out[p + "neg"] = int(np.sum(y_true == 0))
    out[p + "pos_ratio"] = float(np.mean(y_true == 1)) if len(y_true) else np.nan
    out[p + "threshold"] = float(threshold)

    if len(y_true) == 0 or len(np.unique(y_true)) < 2:
        out[p + "roc_auc"] = np.nan
        out[p + "pr_auc"] = np.nan
    else:
        out[p + "roc_auc"] = float(roc_auc_score(y_true, y_score))
        out[p + "pr_auc"] = float(average_precision_score(y_true, y_score))

    out[p + "mcc"] = float(matthews_corrcoef(y_true, y_pred)) if len(y_true) else np.nan
    out[p + "f1"] = float(f1_score(y_true, y_pred, zero_division=0)) if len(y_true) else np.nan
    out[p + "accuracy"] = float(accuracy_score(y_true, y_pred)) if len(y_true) else np.nan
    out[p + "balanced_accuracy"] = float(balanced_accuracy_score(y_true, y_pred)) if len(y_true) else np.nan

    try:
        eps_score = np.clip(y_score, 1e-7, 1 - 1e-7)
        out[p + "log_loss"] = float(log_loss(y_true, eps_score, labels=[0, 1]))
    except Exception:
        out[p + "log_loss"] = np.nan

    # Duplicate short names for compatibility with previous result files.
    out[p + "roc"] = out[p + "roc_auc"]
    out[p + "pr"] = out[p + "pr_auc"]
    return out


def screening_metrics(y_true, y_score, prefix: str = "") -> Dict[str, float]:
    y_true = np.asarray(y_true).astype(int)
    y_score = np.asarray(y_score).astype(float)
    n = len(y_true)
    out = {}
    p = prefix
    base_rate = float(np.mean(y_true == 1)) if n else np.nan
    order = np.argsort(-y_score)

    for pct, label in [(0.01, "1pct"), (0.05, "5pct"), (0.10, "10pct")]:
        k = max(1, int(math.ceil(n * pct))) if n else 0
        if k == 0:
            hit_rate = np.nan
            ef = np.nan
            hits = 0
        else:
            top = order[:k]
            hits = int(np.sum(y_true[top] == 1))
            hit_rate = float(hits / k)
            ef = float(hit_rate / base_rate) if base_rate and base_rate > 0 else np.nan
        out[p + f"top_{label}_n"] = int(k)
        out[p + f"top_{label}_hits"] = int(hits)
        out[p + f"hit_rate_top_{label}"] = hit_rate
        out[p + f"ef_{label}"] = ef

    # Names requested in the plan/table.
    out[p + "EF1%"] = out[p + "ef_1pct"]
    out[p + "EF5%"] = out[p + "ef_5pct"]
    out[p + "Hit_rate@Top1%"] = out[p + "hit_rate_top_1pct"]
    out[p + "Hit_rate@Top5%"] = out[p + "hit_rate_top_5pct"]
    return out


def best_threshold_by_val_f1(y_true, y_score) -> float:
    y_true = np.asarray(y_true).astype(int)
    y_score = np.asarray(y_score).astype(float)
    if len(np.unique(y_true)) < 2:
        return 0.5
    precision, recall, thresholds = precision_recall_curve(y_true, y_score)
    if thresholds.size == 0:
        return 0.5
    f1 = 2 * precision[:-1] * recall[:-1] / np.maximum(precision[:-1] + recall[:-1], 1e-12)
    return float(thresholds[int(np.nanargmax(f1))])


