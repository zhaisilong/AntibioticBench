def run_one(run: Dict, args) -> Optional[Dict]:
    model_name = args.model.lower()
    dataset_name = run["dataset_name"]
    genus = run["genus"]
    split_type = run["split_type"]
    seed = run["seed"]
    threshold_from_name = run["threshold"]

    outdir = Path(args.outdir) / model_name / dataset_name / "classification" / split_type / f"seed_{seed}"
    ensure_dir(outdir)

    print("\n" + "=" * 100, flush=True)
    print(f"[{now()}] RUN: model={model_name} | dataset={dataset_name} | split={split_type} | seed={seed}", flush=True)
    print("=" * 100, flush=True)

    train_df = pd.read_csv(run["train_csv"])
    val_df = pd.read_csv(run["val_csv"])
    test_df = pd.read_csv(run["test_csv"])

    # Hard-coded modeling columns.
    # The model input is always train/val/test["smiles"], and the binary label is always ["active"].
    # Command-line --smiles-col and --target-col are intentionally ignored for reproducibility.
    smiles_col, target_col = require_hardcoded_model_columns(train_df, val_df, test_df)
    value_col = find_col(train_df, args.value_col, DEFAULT_VALUE_COLS, required=False)
    logmic_col = find_col(train_df, args.logmic_col, DEFAULT_LOGMIC_COLS, required=False)

    # Save exact split copies for reproducibility.
    train_df.to_csv(outdir / "train_input.csv", index=False)
    val_df.to_csv(outdir / "validation_input.csv", index=False)
    test_df.to_csv(outdir / "test_input.csv", index=False)

    y_train = train_df[target_col].astype(int).values
    y_val = val_df[target_col].astype(int).values
    y_test = test_df[target_col].astype(int).values

    print(f"[{now()}] Columns: smiles_col={smiles_col}, target_col={target_col}, value_col={value_col}, logmic_col={logmic_col}", flush=True)
    for name, y in [("train", y_train), ("validation", y_val), ("test", y_test)]:
        print(f"[{now()}] {name}: n={len(y)}, pos={int(np.sum(y==1))}, neg={int(np.sum(y==0))}, pos_ratio={float(np.mean(y==1)):.4f}", flush=True)

    all_smiles = pd.concat([train_df[smiles_col], val_df[smiles_col], test_df[smiles_col]], ignore_index=True).astype(str).tolist()
    X_all, _, _ = build_features(all_smiles)
    n_tr, n_val = len(train_df), len(val_df)
    X_train_raw = X_all[:n_tr]
    X_val_raw = X_all[n_tr:n_tr + n_val]
    X_test_raw = X_all[n_tr + n_val:]

    imputer, scaler, X_train, X_val, X_test, X_train_for_pred = fit_preprocess(
        X_train_raw, X_val_raw, X_test_raw, X_train_raw, model_name
    )

    neg = np.sum(y_train == 0)
    pos = np.sum(y_train == 1)
    scale_pos_weight = float(neg / max(pos, 1))

    model = build_model(model_name, random_state=seed if args.use_split_seed_as_model_seed else args.random_state, scale_pos_weight=scale_pos_weight)
    model_params = model.get_params() if hasattr(model, "get_params") else {}
    with open(outdir / "model_params.json", "w", encoding="utf-8") as f:
        json.dump(model_params, f, indent=2, ensure_ascii=False, default=str)

    print(f"[{now()}] Training {model_name} with fixed hyperparameters ...", flush=True)
    t0 = time.time()
    if model_name == "xgb":
        model.fit(X_train, y_train, eval_set=[(X_train, y_train), (X_val, y_val)], verbose=False)
    elif model_name == "lightgbm":
        model.fit(X_train, y_train, eval_set=[(X_train, y_train), (X_val, y_val)], eval_names=["train", "validation"], eval_metric=["binary_logloss", "auc"])
    else:
        model.fit(X_train, y_train)
    train_seconds = time.time() - t0
    print(f"[{now()}] Finished training. seconds={train_seconds:.2f}", flush=True)

    train_score = get_scores(model, X_train)
    val_score = get_scores(model, X_val)
    test_score = get_scores(model, X_test)

    fixed_threshold = 0.5
    val_best_f1_threshold = best_threshold_by_val_f1(y_val, val_score)
    if args.threshold_mode == "val_f1":
        threshold = val_best_f1_threshold
    else:
        threshold = fixed_threshold

    save_training_log(model_name, model, X_train, y_train, X_val, y_val, outdir, threshold=threshold)

    # Boundary and logMIC columns.
    threshold_for_boundary = args.threshold if args.threshold is not None else threshold_from_name
    train_boundary = infer_boundary_flags(train_df, value_col, threshold_for_boundary)
    val_boundary = infer_boundary_flags(val_df, value_col, threshold_for_boundary)
    test_boundary = infer_boundary_flags(test_df, value_col, threshold_for_boundary)
    train_logmic = infer_logmic(train_df, logmic_col, value_col)
    val_logmic = infer_logmic(val_df, logmic_col, value_col)
    test_logmic = infer_logmic(test_df, logmic_col, value_col)

    # NN and activity-cliff diagnostics.
    print(f"[{now()}] Computing nearest-neighbor and activity-cliff diagnostics for validation/test ...", flush=True)
    val_diag = nn_similarity_and_activity_cliff(train_df, val_df, train_score, val_score, smiles_col, target_col, train_logmic, val_logmic)
    test_diag = nn_similarity_and_activity_cliff(train_df, test_df, train_score, test_score, smiles_col, target_col, train_logmic, test_logmic)

    # Prediction files include original metadata + diagnostic fields.
    def make_pred_df(df, scores, split_name, boundary, logmic, diag=None):
        pred = df.copy()
        pred.insert(0, "split", split_name)
        pred["dataset_name"] = dataset_name
        pred["genus"] = genus
        pred["split_type"] = split_type
        pred["seed"] = seed
        pred["model"] = model_name
        pred["true_active"] = df[target_col].astype(int).values
        pred["pred_score"] = scores
        pred["pred_label"] = (scores >= threshold).astype(int)
        pred["pred_label_0p5"] = (scores >= 0.5).astype(int)
        pred["threshold_used"] = threshold
        pred["val_best_f1_threshold"] = val_best_f1_threshold
        pred["error"] = (pred["true_active"].astype(int) != pred["pred_label"].astype(int)).astype(int)
        pred["boundary_flag"] = boundary.values
        pred["log2_mic_for_diagnosis"] = logmic.values
        if diag is not None:
            pred = pd.concat([pred.reset_index(drop=True), diag.reset_index(drop=True)], axis=1)
        return pred

    train_pred_df = make_pred_df(train_df, train_score, "train", train_boundary, train_logmic, diag=None)
    val_pred_df = make_pred_df(val_df, val_score, "validation", val_boundary, val_logmic, diag=val_diag)
    test_pred_df = make_pred_df(test_df, test_score, "test", test_boundary, test_logmic, diag=test_diag)

    train_pred_df.to_csv(outdir / "predictions_train.csv", index=False)
    val_pred_df.to_csv(outdir / "predictions_validation.csv", index=False)
    test_pred_df.to_csv(outdir / "predictions_test.csv", index=False)

    # Main metrics.
    row = {
        "model": model_name,
        "dataset_name": dataset_name,
        "genus": genus,
        "task": "classification",
        "split_type": split_type,
        "seed": seed,
        "threshold_from_dataset_name": threshold_from_name,
        "threshold_for_boundary": threshold_for_boundary,
        "threshold_mode": args.threshold_mode,
        "threshold_used": threshold,
        "val_best_f1_threshold": val_best_f1_threshold,
        "train_seconds": train_seconds,
        "feature_type": "Morgan_r2_2048_plus_RDKit2D",
        "scale_pos_weight": scale_pos_weight,
    }
    for split_name, y, score in [("train", y_train, train_score), ("val", y_val, val_score), ("test", y_test, test_score)]:
        row.update(binary_metrics(y, score, threshold=threshold, prefix=f"{split_name}_"))
        row.update(screening_metrics(y, score, prefix=f"{split_name}_"))

    # Requested diagnostic metrics.
    diag_summary = diagnostic_summary(test_pred_df, y_col="true_active", score_col="pred_score", pred_col="pred_label")
    row.update(diag_summary)

    if args.compute_modi:
        print(f"[{now()}] Computing MODI / landscape roughness ...", flush=True)
        full_for_modi = pd.concat([train_df, val_df, test_df], ignore_index=True)
        modi = compute_modi(full_for_modi, smiles_col=smiles_col, target_col=target_col, k=args.modi_k)
        row.update(modi)
        pd.DataFrame([modi]).to_csv(outdir / "landscape_roughness_modi.csv", index=False)

    metrics_df = pd.DataFrame([row])
    metrics_df.to_csv(outdir / "metrics_full.csv", index=False)
    pd.DataFrame([diag_summary]).to_csv(outdir / "diagnostics_metrics.csv", index=False)

    # Detailed subgroup files for failure diagnosis.
    subgroup_rows = []
    for group_col, group_type in [("boundary_flag", "MIC_boundary"), ("nn_bin", "NN_similarity"), ("ac_flag", "Activity_cliff")]:
        if group_col in test_pred_df.columns:
            for group_value, g in test_pred_df.groupby(group_col, dropna=False):
                r = {"group_type": group_type, "group_col": group_col, "group_value": group_value, "n": int(len(g))}
                r["error_rate"] = float(g["error"].mean()) if len(g) else np.nan
                if len(g) and len(np.unique(g["true_active"].astype(int))) >= 2:
                    r["pr_auc"] = float(average_precision_score(g["true_active"].astype(int), g["pred_score"].astype(float)))
                    r["roc_auc"] = float(roc_auc_score(g["true_active"].astype(int), g["pred_score"].astype(float)))
                    r.update(screening_metrics(g["true_active"].astype(int), g["pred_score"].astype(float), prefix=""))
                subgroup_rows.append(r)
    if subgroup_rows:
        pd.DataFrame(subgroup_rows).to_csv(outdir / "diagnostic_subgroup_metrics.csv", index=False)

    # Reproducibility information.
    run_info = {
        "script": Path(__file__).name,
        "start_or_finish_time": now(),
        "data_root": str(args.data_root),
        "dataset_name": dataset_name,
        "genus": genus,
        "classification_seed_dir": str(run["seed_dir"]),
        "train_csv": str(run["train_csv"]),
        "validation_csv": str(run["val_csv"]),
        "test_csv": str(run["test_csv"]),
        "model": model_name,
        "feature_type": "Morgan fingerprint radius=2 nBits=2048 + RDKit 2D descriptors",
        "smiles_col": smiles_col,
        "target_col": target_col,
        "value_col": value_col,
        "logmic_col": logmic_col,
        "threshold_mode": args.threshold_mode,
        "threshold_used": threshold,
        "random_state": seed if args.use_split_seed_as_model_seed else args.random_state,
        "train_seconds": train_seconds,
        "python": sys.version,
    }
    run_info = sanitize_metadata(run_info)
    with open(outdir / "run_info.json", "w", encoding="utf-8") as f:
        json.dump(run_info, f, indent=2, ensure_ascii=False, default=str)

    joblib.dump({"imputer": imputer, "scaler": scaler, "model": model, "run_info": run_info}, outdir / "model.joblib")

    print(f"[{now()}] TEST core metrics: ROC-AUC={row.get('test_roc_auc'):.4f}, PR-AUC={row.get('test_pr_auc'):.4f}, MCC={row.get('test_mcc'):.4f}, F1={row.get('test_f1'):.4f}, EF1%={row.get('test_EF1%'):.4f}, Hit@Top1%={row.get('test_Hit_rate@Top1%'):.4f}", flush=True)
    print(f"[{now()}] Saved outputs to: {outdir.name}", flush=True)
    return row


