def infer_boundary_flags(df: pd.DataFrame, value_col: Optional[str], threshold: Optional[float]) -> pd.Series:
    for c in ["boundary_flag", "mic_boundary_flag", "mic_boundary", "MIC_boundary", "is_boundary"]:
        if c in df.columns:
            return df[c].astype(int)
    if value_col is not None and threshold is not None:
        vals = pd.to_numeric(df[value_col], errors="coerce")
        return ((vals >= threshold / 2.0) & (vals <= threshold * 2.0)).fillna(False).astype(int)
    return pd.Series(np.nan, index=df.index)


def infer_logmic(df: pd.DataFrame, logmic_col: Optional[str], value_col: Optional[str]) -> pd.Series:
    if logmic_col is not None:
        return pd.to_numeric(df[logmic_col], errors="coerce")
    if value_col is not None:
        vals = pd.to_numeric(df[value_col], errors="coerce")
        return np.log2(vals.where(vals > 0))
    return pd.Series(np.nan, index=df.index)


def nn_similarity_and_activity_cliff(
    train_df: pd.DataFrame,
    eval_df: pd.DataFrame,
    train_scores: np.ndarray,
    eval_scores: np.ndarray,
    smiles_col: str,
    target_col: str,
    logmic_train: pd.Series,
    logmic_eval: pd.Series,
) -> pd.DataFrame:
    train_smiles = train_df[smiles_col].astype(str).tolist()
    eval_smiles = eval_df[smiles_col].astype(str).tolist()
    train_fps = build_bitvectors(train_smiles)
    eval_fps = build_bitvectors(eval_smiles)

    rows = []
    y_train = train_df[target_col].astype(int).values
    train_logmic_arr = pd.to_numeric(logmic_train, errors="coerce").values.astype(float)
    eval_logmic_arr = pd.to_numeric(logmic_eval, errors="coerce").values.astype(float)

    for i, fp in enumerate(eval_fps):
        sims = tanimoto_to_train(fp, train_fps)
        if len(sims):
            nn_idx = int(np.argmax(sims))
            nn_sim = float(sims[nn_idx])
        else:
            nn_idx = -1
            nn_sim = np.nan

        # Activity cliff relative to training set.
        ac_mask = np.zeros(len(train_df), dtype=bool)
        ac_max_abs_diff = np.nan
        ac_pair_directional_correct = []
        if np.isfinite(eval_logmic_arr[i]):
            sim_mask = sims >= 0.7
            diff = np.abs(train_logmic_arr - eval_logmic_arr[i])
            ac_mask = sim_mask & np.isfinite(diff) & (diff >= 4.0)
            if np.any(ac_mask):
                ac_max_abs_diff = float(np.nanmax(diff[ac_mask]))
                ac_indices = np.where(ac_mask)[0]
                for j in ac_indices:
                    # Lower logMIC means stronger activity; higher predicted score means stronger active probability.
                    true_test_stronger = eval_logmic_arr[i] < train_logmic_arr[j]
                    pred_test_stronger = eval_scores[i] > train_scores[j]
                    ac_pair_directional_correct.append(int(true_test_stronger == pred_test_stronger))

        rows.append({
            "nn_train_row": nn_idx,
            "nn_sim": nn_sim,
            "nn_bin": ">=0.7" if nn_sim >= 0.7 else ("0.4-0.7" if nn_sim >= 0.4 else "<0.4"),
            "nn_train_smiles": train_smiles[nn_idx] if nn_idx >= 0 else None,
            "nn_train_active": int(y_train[nn_idx]) if nn_idx >= 0 else np.nan,
            "nn_train_score": float(train_scores[nn_idx]) if nn_idx >= 0 else np.nan,
            "nn_train_log2mic": float(train_logmic_arr[nn_idx]) if nn_idx >= 0 and np.isfinite(train_logmic_arr[nn_idx]) else np.nan,
            "ac_flag": int(np.any(ac_mask)),
            "ac_neighbor_count": int(np.sum(ac_mask)),
            "ac_max_abs_log2mic_diff": ac_max_abs_diff,
            "ac_pair_directional_accuracy_for_molecule": float(np.mean(ac_pair_directional_correct)) if ac_pair_directional_correct else np.nan,
            "ac_pair_count_for_molecule": int(len(ac_pair_directional_correct)),
        })
    return pd.DataFrame(rows)


def diagnostic_summary(pred_df: pd.DataFrame, y_col: str = "true_active", score_col: str = "pred_score", pred_col: str = "pred_label") -> Dict[str, float]:
    out = {}
    df = pred_df.copy()
    df["error"] = (df[y_col].astype(int) != df[pred_col].astype(int)).astype(int)

    # 12.1 MIC-boundary error analysis
    if "boundary_flag" in df.columns and df["boundary_flag"].notna().any():
        b = df[df["boundary_flag"] == 1]
        nb = df[df["boundary_flag"] == 0]
        out["boundary_n"] = int(len(b))
        out["non_boundary_n"] = int(len(nb))
        out["boundary_error_rate"] = float(b["error"].mean()) if len(b) else np.nan
        out["non_boundary_error_rate"] = float(nb["error"].mean()) if len(nb) else np.nan
        out["boundary_error_enrichment"] = (
            out["boundary_error_rate"] / out["non_boundary_error_rate"]
            if out["non_boundary_error_rate"] and out["non_boundary_error_rate"] > 0 else np.nan
        )

    # 12.2 NN error, PR-AUC and virtual-screening enrichment groups
    # These subgroup metrics are also used by 12.4 Perimeter OOD error analysis,
    # especially the low-training-similarity subgroup: NN_sim < 0.4.
    if "nn_bin" in df.columns:
        for bin_name in [">=0.7", "0.4-0.7", "<0.4"]:
            g = df[df["nn_bin"] == bin_name]
            key = bin_name.replace(">=", "ge_").replace("<", "lt_").replace("-", "_").replace(".", "p")
            prefix = f"nn_{key}_"
            out[prefix + "n"] = int(len(g))
            out[prefix + "error_rate"] = float(g["error"].mean()) if len(g) else np.nan
            if len(g) and len(np.unique(g[y_col].astype(int))) >= 2:
                y_g = g[y_col].astype(int).values
                score_g = g[score_col].astype(float).values
                out[prefix + "pr_auc"] = float(average_precision_score(y_g, score_g))
                out.update(screening_metrics(y_g, score_g, prefix=prefix))
            else:
                out[prefix + "pr_auc"] = np.nan
                for suffix in [
                    "top_1pct_n", "top_1pct_hits", "hit_rate_top_1pct", "ef_1pct",
                    "top_5pct_n", "top_5pct_hits", "hit_rate_top_5pct", "ef_5pct",
                    "top_10pct_n", "top_10pct_hits", "hit_rate_top_10pct", "ef_10pct",
                    "EF1%", "EF5%", "Hit_rate@Top1%", "Hit_rate@Top5%",
                ]:
                    out[prefix + suffix] = np.nan

    # 12.3 AC subgroup and directional accuracy
    if "ac_flag" in df.columns:
        ac = df[df["ac_flag"] == 1]
        non_ac = df[df["ac_flag"] == 0]
        out["ac_n"] = int(len(ac))
        out["non_ac_n"] = int(len(non_ac))
        out["ac_error_rate"] = float(ac["error"].mean()) if len(ac) else np.nan
        out["non_ac_error_rate"] = float(non_ac["error"].mean()) if len(non_ac) else np.nan
        out["ac_error_enrichment"] = (
            out["ac_error_rate"] / out["non_ac_error_rate"]
            if out["non_ac_error_rate"] and out["non_ac_error_rate"] > 0 else np.nan
        )
        if len(ac) and len(np.unique(ac[y_col].astype(int))) >= 2:
            out["ac_subgroup_pr_auc"] = float(average_precision_score(ac[y_col].astype(int), ac[score_col].astype(float)))
        else:
            out["ac_subgroup_pr_auc"] = np.nan
        if "ac_pair_directional_accuracy_for_molecule" in df.columns:
            out["ac_pair_directional_accuracy"] = float(df["ac_pair_directional_accuracy_for_molecule"].dropna().mean()) if df["ac_pair_directional_accuracy_for_molecule"].notna().any() else np.nan
            out["ac_pair_total_count"] = int(df.get("ac_pair_count_for_molecule", pd.Series(dtype=float)).fillna(0).sum())

    return out


def compute_modi(df: pd.DataFrame, smiles_col: str, target_col: str, k: int = 10) -> Dict[str, float]:
    smiles = df[smiles_col].astype(str).tolist()
    y = df[target_col].astype(int).values
    fps = build_bitvectors(smiles)
    consistencies = []
    for i, fp in enumerate(fps):
        sims = tanimoto_to_train(fp, fps)
        if len(sims) <= 1:
            continue
        sims[i] = -1.0
        nn_idx = np.argsort(-sims)[:min(k, len(sims) - 1)]
        consistencies.append(float(np.mean(y[nn_idx] == y[i])))
    modi = float(np.mean(consistencies)) if consistencies else np.nan
    return {"MODI_k": int(k), "MODI": modi, "landscape_roughness_1_minus_MODI": float(1 - modi) if np.isfinite(modi) else np.nan}


