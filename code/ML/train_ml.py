def now() -> str:
    return time.strftime("%Y-%m-%d %H:%M:%S")


def ensure_dir(path: Path) -> None:
    path.mkdir(parents=True, exist_ok=True)


def numeric_sort_key(path: Path):
    m = re.match(r"^(\d+)_", path.name)
    return (int(m.group(1)) if m else 10**9, path.name)


def parse_threshold_from_dataset_name(name: str) -> Optional[float]:
    m = re.search(r"median_([0-9]+(?:\.[0-9]+)?)", name)
    if m:
        return float(m.group(1))
    return None


def parse_genus_from_dataset_name(name: str) -> str:
    # Example: 1_Staphylococcus_median_16_...
    parts = name.split("_")
    if len(parts) >= 2 and parts[0].isdigit():
        return parts[1]
    return name


def find_col(df: pd.DataFrame, preferred: Optional[str], candidates: List[str], required: bool = True) -> Optional[str]:
    if preferred and preferred in df.columns:
        return preferred
    for c in candidates:
        if c in df.columns:
            return c
    if required:
        raise ValueError(f"Cannot find required column. Preferred={preferred}; candidates={candidates}; columns={list(df.columns)}")
    return None


def require_hardcoded_model_columns(train_df: pd.DataFrame, val_df: pd.DataFrame, test_df: pd.DataFrame) -> Tuple[str, str]:
    """Enforce the benchmark convention: input SMILES = smiles; label = active."""
    smiles_col = HARD_CODED_SMILES_COL
    target_col = HARD_CODED_TARGET_COL
    for split_name, df in [("train", train_df), ("validation", val_df), ("test", test_df)]:
        missing = [c for c in [smiles_col, target_col] if c not in df.columns]
        if missing:
            raise ValueError(
                f"Missing required hard-coded column(s) {missing} in {split_name}. "
                f"This benchmark script requires molecular input column 'smiles' and label column 'active'. "
                f"Available columns: {list(df.columns)}"
            )
    return smiles_col, target_col


