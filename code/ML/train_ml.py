def build_model(model_name: str, random_state: int, scale_pos_weight: Optional[float]) -> object:
    model_name = model_name.lower()
    if model_name == "rf":
        return RandomForestClassifier(
            n_estimators=500,
            max_features="sqrt",
            class_weight="balanced",
            n_jobs=-1,
            random_state=random_state,
        )
    if model_name == "svm":
        return SVC(
            C=1.0,
            kernel="rbf",
            gamma="scale",
            probability=True,
            class_weight="balanced",
            random_state=random_state,
        )
    if model_name == "xgb":
        try:
            from xgboost import XGBClassifier
        except Exception as e:
            raise ImportError("xgboost is required for --model xgb") from e
        return XGBClassifier(
            n_estimators=500,
            learning_rate=0.05,
            max_depth=6,
            subsample=0.9,
            colsample_bytree=0.9,
            objective="binary:logistic",
            eval_metric=["logloss", "auc", "aucpr"],
            tree_method="hist",
            scale_pos_weight=scale_pos_weight,
            random_state=random_state,
            n_jobs=-1,
        )
    if model_name == "lightgbm":
        try:
            from lightgbm import LGBMClassifier
        except Exception as e:
            raise ImportError("lightgbm is required for --model lightgbm") from e
        return LGBMClassifier(
            n_estimators=500,
            learning_rate=0.05,
            num_leaves=31,
            subsample=0.9,
            colsample_bytree=0.9,
            class_weight="balanced",
            random_state=random_state,
            n_jobs=-1,
            verbose=-1,
        )
    raise ValueError(f"Unsupported model: {model_name}")


def fit_preprocess(X_train, X_val, X_test, X_all_for_train_pred, model_name: str):
    imputer = SimpleImputer(strategy="median")
    X_train_i = imputer.fit_transform(X_train)
    X_val_i = imputer.transform(X_val)
    X_test_i = imputer.transform(X_test)
    X_all_i = imputer.transform(X_all_for_train_pred)

    scaler = None
    if model_name.lower() == "svm":
        scaler = StandardScaler()
        X_train_i = scaler.fit_transform(X_train_i)
        X_val_i = scaler.transform(X_val_i)
        X_test_i = scaler.transform(X_test_i)
        X_all_i = scaler.transform(X_all_i)
    return imputer, scaler, X_train_i, X_val_i, X_test_i, X_all_i


def get_scores(model, X) -> np.ndarray:
    if hasattr(model, "predict_proba"):
        return model.predict_proba(X)[:, 1].astype(float)
    if hasattr(model, "decision_function"):
        s = model.decision_function(X).astype(float)
        s_min, s_max = np.min(s), np.max(s)
        if s_max > s_min:
            return ((s - s_min) / (s_max - s_min)).astype(float)
        return np.full(len(s), 0.5, dtype=float)
    return model.predict(X).astype(float)


def save_training_log(model_name: str, model, X_train, y_train, X_val, y_val, outdir: Path, threshold: float = 0.5):
    """Save train/validation loss curves in a consistent format.

    This always writes:
      - train_log.csv
      - training_curve.csv
      - train_log_long.csv

    For XGBoost/LightGBM, rows are boosting iterations.
    For RF/SVM, there is no epoch-wise training history, so one final row is written.
    """
    mname = model_name.lower()
    long_rows = []
    wide_by_iter = {}

    def split_alias(raw_split: str, split_index: int = None) -> str:
        s = str(raw_split).lower()
        if s in {"train", "training", "train_0"}:
            return "train"
        if s in {"valid", "validation", "val", "valid_0", "valid_1"}:
            return "validation"
        if s == "validation_0":
            return "train"
        if s == "validation_1":
            return "validation"
        if split_index == 0:
            return "train"
        if split_index == 1:
            return "validation"
        if "train" in s:
            return "train"
        if "valid" in s or "val" in s:
            return "validation"
        return str(raw_split)

    def metric_alias(raw_metric: str) -> str:
        s = str(raw_metric).lower()
        if s in {"logloss", "binary_logloss", "log_loss", "multi_logloss"}:
            return "loss"
        if s in {"auc", "roc_auc"}:
            return "auc"
        if s in {"aucpr", "average_precision", "pr_auc", "average_precision_score"}:
            return "pr_auc"
        return s

    def add_metric(iteration: int, raw_split: str, raw_metric: str, value, split_index: int = None):
        try:
            value = float(value)
        except Exception:
            value = np.nan

        split = split_alias(raw_split, split_index)
        metric = metric_alias(raw_metric)

        long_rows.append({
            "iteration": int(iteration),
            "raw_split": str(raw_split),
            "split": split,
            "raw_metric": str(raw_metric),
            "metric": metric,
            "value": value,
        })

        row = wide_by_iter.setdefault(int(iteration), {"iteration": int(iteration)})
        if split == "train":
            if metric == "loss":
                row["train_loss"] = value
                row["train_log_loss"] = value
            elif metric == "auc":
                row["train_auc"] = value
            elif metric == "pr_auc":
                row["train_pr_auc"] = value
        elif split == "validation":
            if metric == "loss":
                row["val_loss"] = value
                row["val_log_loss"] = value
            elif metric == "auc":
                row["val_auc"] = value
            elif metric == "pr_auc":
                row["val_pr_auc"] = value

    if mname == "xgb" and hasattr(model, "evals_result"):
        try:
            res = model.evals_result()
            for split_index, (split_key, metrics) in enumerate(res.items()):
                for metric_name, vals in metrics.items():
                    for i, v in enumerate(vals):
                        add_metric(i + 1, split_key, metric_name, v, split_index=split_index)
        except Exception as e:
            long_rows.append({
                "iteration": 1,
                "raw_split": "NA",
                "split": "NA",
                "raw_metric": "evals_result_error",
                "metric": "error",
                "value": np.nan,
                "note": type(e).__name__,
            })

    elif mname == "lightgbm" and hasattr(model, "evals_result_"):
        try:
            res = model.evals_result_
            for split_index, (split_key, metrics) in enumerate(res.items()):
                for metric_name, vals in metrics.items():
                    for i, v in enumerate(vals):
                        add_metric(i + 1, split_key, metric_name, v, split_index=split_index)
        except Exception as e:
            long_rows.append({
                "iteration": 1,
                "raw_split": "NA",
                "split": "NA",
                "raw_metric": "evals_result_error",
                "metric": "error",
                "value": np.nan,
                "note": type(e).__name__,
            })

    if not wide_by_iter:
        train_score = get_scores(model, X_train)
        val_score = get_scores(model, X_val)
        train_m = binary_metrics(y_train, train_score, threshold=threshold, prefix="")
        val_m = binary_metrics(y_val, val_score, threshold=threshold, prefix="")

        wide_by_iter[1] = {
            "iteration": 1,
            "train_loss": train_m.get("log_loss", np.nan),
            "val_loss": val_m.get("log_loss", np.nan),
            "train_log_loss": train_m.get("log_loss", np.nan),
            "val_log_loss": val_m.get("log_loss", np.nan),
            "train_auc": train_m.get("roc_auc", np.nan),
            "val_auc": val_m.get("roc_auc", np.nan),
            "train_pr_auc": train_m.get("pr_auc", np.nan),
            "val_pr_auc": val_m.get("pr_auc", np.nan),
            "train_mcc": train_m.get("mcc", np.nan),
            "val_mcc": val_m.get("mcc", np.nan),
            "train_f1": train_m.get("f1", np.nan),
            "val_f1": val_m.get("f1", np.nan),
            "note": "final_only_no_epoch_loss_for_this_model",
        }

        for split_name, metrics in [("train", train_m), ("validation", val_m)]:
            for metric_name, value in metrics.items():
                try:
                    value = float(value)
                except Exception:
                    value = np.nan
                long_rows.append({
                    "iteration": 1,
                    "raw_split": split_name,
                    "split": split_name,
                    "raw_metric": metric_name,
                    "metric": metric_alias(metric_name),
                    "value": value,
                    "note": "final_only_no_epoch_loss_for_this_model",
                })

    curve = pd.DataFrame([wide_by_iter[k] for k in sorted(wide_by_iter)])
    preferred_cols = [
        "iteration",
        "train_loss", "val_loss",
        "train_log_loss", "val_log_loss",
        "train_auc", "val_auc",
        "train_pr_auc", "val_pr_auc",
        "train_mcc", "val_mcc",
        "train_f1", "val_f1",
        "note",
    ]
    ordered_cols = [c for c in preferred_cols if c in curve.columns] + [c for c in curve.columns if c not in preferred_cols]
    curve = curve[ordered_cols]

    curve.to_csv(outdir / "train_log.csv", index=False)
    curve.to_csv(outdir / "training_curve.csv", index=False)
    pd.DataFrame(long_rows).to_csv(outdir / "train_log_long.csv", index=False)


